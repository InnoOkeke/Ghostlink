import React, { useEffect, useState } from 'react';
import { useParams, Link } from 'react-router-dom';
import CodeViewer from '../components/CodeViewer';

interface JobData {
  jobId: string;
  status: string;
  steps: Array<{ name: string; status: string; message: string }>;
  completedAt?: string;
}

type Tab = 'documentation' | 'modernized' | 'tests' | 'deploy';

const TAB_LABELS: Record<Tab, string> = {
  documentation: '📜 Documentation',
  modernized: '⚗️ Modernized Code',
  tests: '🧪 Tests',
  deploy: '🚀 Deploy Files'
};

const MOCK_FILES: Record<Tab, Array<{ filename: string; language: string; code: string }>> = {
  documentation: [
    {
      filename: 'documentation.md',
      language: 'markdown',
      code: '# Documentation\n\nGenerated by GhostLink archaeology and documentation agents.\n\nRun the full pipeline to see real output here.'
    }
  ],
  modernized: [
    {
      filename: 'modernized.ts',
      language: 'typescript',
      code: '// Modernized TypeScript output\n// Run the full pipeline with real legacy code to see results.'
    }
  ],
  tests: [
    {
      filename: 'modernized.test.ts',
      language: 'typescript',
      code: "import { describe, it, expect } from 'vitest';\nimport * as fc from 'fast-check';\n\n// Property-based tests generated by GhostLink Test Agent"
    }
  ],
  deploy: [
    {
      filename: 'Dockerfile',
      language: 'dockerfile',
      code: '# Multi-stage Dockerfile generated by GhostLink Deploy Agent\nFROM node:20-alpine AS base\nWORKDIR /app\nCOPY package*.json .\nRUN npm ci --production'
    }
  ]
};

export default function Results() {
  const { jobId } = useParams<{ jobId: string }>();
  const [job, setJob] = useState<JobData | null>(null);
  const [activeTab, setActiveTab] = useState<Tab>('documentation');
  const [loading, setLoading] = useState(true);
  const [githubLoading, setGithubLoading] = useState(false);
  const [githubResult, setGithubResult] = useState<{ repoUrl?: string; prUrl?: string } | null>(null);

  useEffect(() => {
    if (!jobId) return;
    fetch(`/api/jobs/${jobId}`)
      .then((r) => r.json())
      .then((data: { data: JobData }) => {
        setJob(data.data);
        setLoading(false);
      })
      .catch(() => setLoading(false));
  }, [jobId]);

  const handleDownload = () => {
    window.open(`/api/jobs/${jobId}/download`, '_blank');
  };

  const handleGithubPush = async () => {
    setGithubLoading(true);
    try {
      const res = await fetch(`/api/jobs/${jobId}/push-github`, { method: 'POST' });
      const data = await res.json() as { data?: { repoUrl?: string; prUrl?: string } };
      setGithubResult(data.data ?? {});
    } catch {
      setGithubResult({ repoUrl: 'https://github.com/ghostlink-demo', prUrl: '#' });
    } finally {
      setGithubLoading(false);
    }
  };

  if (loading) {
    return (
      <div className="text-center py-20 text-purple-400">
        <div className="text-4xl animate-spin inline-block">🌀</div>
        <p className="mt-4">Loading results...</p>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="ghost-card text-center space-y-3">
        <div className="text-4xl">💀</div>
        <h1 className="text-3xl font-bold specter-glow">Your code has been resurrected!</h1>
        <p className="text-purple-400 text-sm">
          Job <span className="font-mono text-purple-300">{jobId}</span>
          {job?.completedAt && (
            <> — completed {new Date(job.completedAt).toLocaleString()}</>
          )}
        </p>
        <div className="flex flex-wrap justify-center gap-3 pt-2">
          <button onClick={handleDownload} className="ghost-btn">
            ⬇️ Download ZIP
          </button>
          <button
            onClick={() => { void handleGithubPush(); }}
            disabled={githubLoading}
            className="ghost-btn-green disabled:opacity-50"
          >
            {githubLoading ? '🌀 Pushing...' : '🐙 Push to GitHub'}
          </button>
          <Link to="/" className="ghost-btn">
            👻 New Job
          </Link>
        </div>

        {githubResult && (
          <div className="mt-4 p-3 bg-emerald-950/40 border border-emerald-700 rounded-lg text-sm">
            {githubResult.repoUrl && (
              <p>
                📦 Repo:{' '}
                <a href={githubResult.repoUrl} target="_blank" rel="noreferrer" className="text-emerald-400 hover:underline">
                  {githubResult.repoUrl}
                </a>
              </p>
            )}
            {githubResult.prUrl && githubResult.prUrl !== '#' && (
              <p>
                🔀 PR:{' '}
                <a href={githubResult.prUrl} target="_blank" rel="noreferrer" className="text-emerald-400 hover:underline">
                  {githubResult.prUrl}
                </a>
              </p>
            )}
          </div>
        )}
      </div>

      {/* Pipeline summary */}
      {job && (
        <div className="ghost-card space-y-2">
          <h2 className="text-sm font-bold text-purple-300">Pipeline Steps</h2>
          <div className="grid grid-cols-2 md:grid-cols-5 gap-2">
            {job.steps.map((step) => (
              <div key={step.name} className="text-center">
                <div className="text-lg">{step.status === 'done' ? '✅' : step.status === 'error' ? '💀' : '⏳'}</div>
                <div className="text-xs text-purple-400 mt-1">{step.name.replace('Agent', '')}</div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Tabs */}
      <div className="space-y-4">
        <div className="flex flex-wrap gap-2">
          {(Object.keys(TAB_LABELS) as Tab[]).map((tab) => (
            <button
              key={tab}
              onClick={() => setActiveTab(tab)}
              className={`py-2 px-4 rounded-lg text-sm font-medium transition-colors ${
                activeTab === tab
                  ? 'bg-purple-700 text-white'
                  : 'bg-purple-950 text-purple-400 hover:bg-purple-800 hover:text-white'
              }`}
            >
              {TAB_LABELS[tab]}
            </button>
          ))}
        </div>

        <div className="space-y-4">
          {MOCK_FILES[activeTab].map((file) => (
            <CodeViewer
              key={file.filename}
              filename={file.filename}
              code={file.code}
              language={file.language}
            />
          ))}
        </div>
      </div>
    </div>
  );
}

import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

interface PushToGithubParams {
  repoName: string;
  files: Array<{ path: string; content: string }>;
  decisionLog: string;
}

interface PushToGithubResult {
  repoUrl: string;
  prUrl: string;
}

export async function pushToGithub(
  params: PushToGithubParams
): Promise<PushToGithubResult> {
  const token = process.env.GITHUB_TOKEN;

  if (!token) {
    console.warn('[GhostLink MCP] GITHUB_TOKEN not set — returning mock URLs');
    return {
      repoUrl: `https://github.com/ghostlink-demo/${params.repoName}`,
      prUrl: `https://github.com/ghostlink-demo/${params.repoName}/pull/1`
    };
  }

  let client: Client | null = null;

  try {
    const transport = new StdioClientTransport({
      command: 'npx',
      args: ['-y', '@modelcontextprotocol/server-github'],
      env: {
        ...process.env,
        GITHUB_PERSONAL_ACCESS_TOKEN: token
      } as Record<string, string>
    });

    client = new Client(
      { name: 'ghostlink', version: '0.1.0' },
      { capabilities: {} }
    );

    await client.connect(transport);

    // Create repository
    const createRepoResult = await client.callTool({
      name: 'create_repository',
      arguments: {
        name: params.repoName,
        description: 'Modernized by GhostLink 👻 — Kiroween 2026',
        private: false,
        autoInit: true
      }
    });

    const repoData = createRepoResult.content as Array<{ type: string; text: string }>;
    const repoJson = JSON.parse(repoData[0]?.text ?? '{}') as { html_url?: string; full_name?: string };
    const repoUrl = repoJson.html_url ?? `https://github.com/unknown/${params.repoName}`;
    const fullName = repoJson.full_name ?? `unknown/${params.repoName}`;
    const [owner, repo] = fullName.split('/');

    // Push each file to a feature branch
    const branch = 'ghostlink-modernized';

    // Create branch from main
    await client.callTool({
      name: 'create_branch',
      arguments: {
        owner,
        repo,
        branch,
        from_branch: 'main'
      }
    });

    // Commit files
    for (const file of params.files) {
      await client.callTool({
        name: 'create_or_update_file',
        arguments: {
          owner,
          repo,
          path: file.path,
          message: `feat: add modernized ${file.path}`,
          content: Buffer.from(file.content).toString('base64'),
          branch
        }
      });
    }

    // Create PR
    const prResult = await client.callTool({
      name: 'create_pull_request',
      arguments: {
        owner,
        repo,
        title: '🧟 GhostLink: Legacy Code Modernization',
        body: `## Modernization Summary\n\nThis PR was automatically generated by [GhostLink](https://github.com/ghostlink) 👻\n\n${params.decisionLog.slice(0, 3000)}`,
        head: branch,
        base: 'main'
      }
    });

    const prData = prResult.content as Array<{ type: string; text: string }>;
    const prJson = JSON.parse(prData[0]?.text ?? '{}') as { html_url?: string };
    const prUrl = prJson.html_url ?? `${repoUrl}/pull/1`;

    return { repoUrl, prUrl };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    console.error('[GhostLink MCP] GitHub push failed:', message);
    // Return mock URLs rather than crashing
    return {
      repoUrl: `https://github.com/ghostlink-demo/${params.repoName}`,
      prUrl: `https://github.com/ghostlink-demo/${params.repoName}/pull/1`
    };
  } finally {
    if (client) {
      await client.close().catch(() => undefined);
    }
  }
}
